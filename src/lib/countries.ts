export const COUNTRY_BY_ID = new Map(COUNTRIES.map((c) => [c.id, c]));

function normalizeName(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
}

export function recordForFeature(id: string, topologyName: string) {
  const record = COUNTRY_BY_ID.get(id);
  if (!record) return undefined;
  const featureName = normalizeName(topologyName);
  const names = [record.name, ...(record.aliases ?? [])].map(normalizeName);
  if (names.some((name) => name === featureName || featureName.includes(name) || name.includes(featureName))) {
    return record;
  }
  return undefined;
}

export function countryMatchesQuery(country: CountryRecord, query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return false;
  if (country.name.toLowerCase().includes(q)) return true;
  if (country.iso3.toLowerCase().includes(q)) return true;
  return Boolean(country.aliases?.some((a) => a.toLowerCase().includes(q)));
}
